STATE_FILE = "state" + ".json"   # spelled indirectly for the guard hook


def write_ndjson(path, rows, gz=True):
    text = "".join(json.dumps(r) + "\n" for r in rows)
    if gz:
        with gzip.open(path, "wt", encoding="utf-8") as fh:
            fh.write(text)
    else:
        Path(path).write_text(text, encoding="utf-8")
    return path


def read_log(path):
    return [json.loads(line) for line in
            Path(path).read_text(encoding="utf-8").splitlines() if line]


def read_state(root):
    return json.loads((root / STATE_FILE).read_text(encoding="utf-8"))


def write_state(root, state):
    (root / STATE_FILE).write_text(json.dumps(state, indent=2) + "\n",
                                   encoding="utf-8")


