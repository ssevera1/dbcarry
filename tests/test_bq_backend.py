def test_run_ddl_views_and_row_policies(tmp_path, emu):
    emu.create_dataset("retail")
    emu.run_ddl(ORDERS_DDL)
    emu.run_ddl("CREATE OR REPLACE VIEW `proj.retail.recent_orders` AS "
                "SELECT id FROM `proj.retail.orders` WHERE region = 'eu';")
    emu.run_ddl("CREATE MATERIALIZED VIEW IF NOT EXISTS "
                "`proj.retail.order_totals`\n"
                "OPTIONS (description = 'totals (by status)')\n"
                "AS SELECT status, COUNT(*) AS n FROM `proj.retail.orders` "
                "GROUP BY status")
    tables = {t["name"]: t["type"] for t in emu.list_tables("retail")}
    assert tables == {"orders": "TABLE", "recent_orders": "VIEW",
                      "order_totals": "MATERIALIZED_VIEW"}
    views = read_state(tmp_path / "emu")["datasets"]["retail"]["tables"]
    assert views["recent_orders"]["body"] == \
        "SELECT id FROM `proj.retail.orders` WHERE region = 'eu'"
    assert views["order_totals"]["body"].startswith("SELECT status, COUNT(*)")
    # OR REPLACE replaces, IF NOT EXISTS keeps the first body
    emu.run_ddl("CREATE OR REPLACE VIEW `proj.retail.recent_orders` AS "
                "SELECT 2")
    emu.run_ddl("CREATE MATERIALIZED VIEW IF NOT EXISTS "
                "`proj.retail.order_totals` AS SELECT 3")
    views = read_state(tmp_path / "emu")["datasets"]["retail"]["tables"]
    assert views["recent_orders"]["body"] == "SELECT 2"
    assert views["order_totals"]["body"].startswith("SELECT status")
    with pytest.raises(bb.BackendError, match="already exists"):
        emu.run_ddl("CREATE VIEW `proj.retail.recent_orders` AS SELECT 4")

    emu.run_ddl('CREATE ROW ACCESS POLICY rls_reporting ON '
                '`proj.retail.orders` GRANT TO ("group:a@x", "group:b@x") '
                "FILTER USING (region = 'eu');")
    emu.run_ddl("CREATE OR REPLACE ROW ACCESS POLICY rls_all ON "
                "`proj.retail.orders`\n  GRANT TO ('group:c@x')\n"
                "  FILTER USING (TRUE)")
    assert emu.list_row_policies("retail", "orders") == [
        {"name": "rls_reporting", "members": ["group:a@x", "group:b@x"],
         "filter": "region = 'eu'"},
        {"name": "rls_all", "members": ["group:c@x"], "filter": "TRUE"}]
    # a duplicate policy without OR REPLACE is an error, as on BigQuery
    with pytest.raises(bb.BackendError, match="already exists"):
        emu.run_ddl("CREATE ROW ACCESS POLICY rls_all ON `proj.retail.orders`"
                    " GRANT TO ('group:c@x') FILTER USING (FALSE)")
    emu.run_ddl("CREATE ROW ACCESS POLICY IF NOT EXISTS rls_all ON "
                "`proj.retail.orders` GRANT TO ('group:z@x') "
                "FILTER USING (FALSE)")
    assert emu.list_row_policies("retail", "orders")[1]["filter"] == "TRUE"
    with pytest.raises(bb.BackendError, match="not found"):
        emu.run_ddl("CREATE ROW ACCESS POLICY p ON `proj.retail.nope` "
                    "GRANT TO ('group:z@x') FILTER USING (TRUE)")

    unsupported = "ALTER TABLE `proj.retail.orders` ADD COLUMN extra STRING"
    with pytest.raises(bb.BackendError) as ei:
        emu.run_ddl(unsupported)
    assert unsupported[:80] in str(ei.value)
    long_stmt = "DROP TABLE `proj.retail.orders` " + "x" * 200
    with pytest.raises(bb.BackendError) as ei:
        emu.run_ddl(long_stmt)
    assert long_stmt[:80] in str(ei.value)
    assert long_stmt[:120] not in str(ei.value)


