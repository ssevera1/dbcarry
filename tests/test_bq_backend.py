def test_emulated_end_to_end(tmp_path, emu):
    emu.create_dataset("retail")
    assert emu.list_datasets() == ["retail"]
    emu.run_ddl(CUSTOMERS_DDL)
    emu.run_ddl(ORDERS_DDL)
    assert [t["name"] for t in emu.list_tables("retail")] == \
        ["customers", "orders"]
    assert all(t["type"] == "TABLE" for t in emu.list_tables("retail"))

    fields = emu.get_table_schema("retail", "orders")
    assert fields[0] == {"name": "id", "type": "INT64", "mode": "REQUIRED"}
    by_name = {f["name"]: f for f in fields}
    assert by_name["actor"]["mode"] == "NULLABLE"
    assert by_name["tags"]["type"] == "STRING"
    assert by_name["tags"]["mode"] == "REPEATED"
    assert by_name["ordered_at"]["type"] == "TIMESTAMP"

    # bindings at every scope, idempotent
    emu.add_table_binding("retail", "orders", bb.ROLE_VIEWER, REPORTING)
    emu.add_table_binding("retail", "orders", bb.ROLE_VIEWER, REPORTING)
    assert emu.get_table_bindings("retail", "orders") == [
        {"role": bb.ROLE_VIEWER, "member": REPORTING}]
    emu.add_dataset_access("retail", {"role": bb.ROLE_EDITOR, "member": RW})
    emu.add_dataset_access("retail", {"role": bb.ROLE_VIEWER, "member": RO})
    emu.add_dataset_access("retail", {"role": bb.ROLE_VIEWER, "member": RO})
    access = emu.get_dataset_access("retail")
    assert {"role": bb.ROLE_EDITOR, "member": RW} in access
    assert len(access) == 2
    emu.add_project_binding(bb.ROLE_JOBUSER, RW)
    emu.add_project_binding(bb.ROLE_JOBUSER, RW)
    assert emu.get_project_bindings() == [
        {"role": bb.ROLE_JOBUSER, "member": RW}]

    # taxonomy with enforcement activated, one tag, one reader
    tax = emu.create_taxonomy("dbdrift_demo", ["FINE_GRAINED_ACCESS_CONTROL"])
    assert tax.startswith("projects/proj/locations/US/taxonomies/")
    desc = emu.describe_taxonomy(tax)
    assert desc["displayName"] == "dbdrift_demo"
    assert desc["activatedPolicyTypes"] == ["FINE_GRAINED_ACCESS_CONTROL"]
    assert [t["name"] for t in emu.list_taxonomies()] == [tax]
    tag = emu.create_policy_tag(tax, "customers__email", "restricted column")
    assert tag.startswith(tax + "/policyTags/")
    assert emu.list_policy_tags(tax) == [
        {"name": tag, "displayName": "customers__email",
         "description": "restricted column"}]
    emu.add_policy_tag_binding(tag, bb.ROLE_FGR, RW)
    assert emu.get_policy_tag_bindings(tag) == [
        {"role": bb.ROLE_FGR, "member": RW}]
    cfields = emu.get_table_schema("retail", "customers")
    for f in cfields:
        if f["name"] == "email":
            f["policyTags"] = {"names": [tag]}
    emu.update_table_schema("retail", "customers", cfields)
    email = [f for f in emu.get_table_schema("retail", "customers")
             if f["name"] == "email"][0]
    assert email["policyTags"] == {"names": [tag]}

    # row policies
    emu.create_row_policy("retail", "orders", "rls_reporting", [REPORTING],
                          "region = 'eu'")
    emu.create_row_policy("retail", "orders", "rls_app_rw", [RW], "TRUE")
    assert emu.list_row_policies("retail", "orders") == [
        {"name": "rls_reporting", "members": [REPORTING],
         "filter": "region = 'eu'"},
        {"name": "rls_app_rw", "members": [RW], "filter": "TRUE"}]

    # load and count
    ndjson = write_ndjson(tmp_path / "orders.ndjson.gz", ORDER_ROWS)
    assert emu.load_ndjson("retail", "orders", ndjson, fields) == 3
    assert emu.count_rows("retail", "orders") == 3
    assert (tmp_path / "emu" / "data" / "retail" / "orders.ndjson.gz").exists()

    # probes: named principals see their policy rows
    res = emu.probe(RW, "", "retail", "orders", ["id"])
    assert (res["status"], res["row_count"]) == ("ok", 3)
    res = emu.probe(REPORTING, "", "retail", "orders", ["id", "region"])
    assert (res["status"], res["row_count"]) == ("ok", 1)
    # readable but unnamed by any policy: zero rows, no error
    res = emu.probe(RO, "", "retail", "orders", ["id"])
    assert (res["status"], res["row_count"]) == ("ok", 0)
    # no binding at all: denied
    res = emu.probe(OUTSIDER, "", "retail", "orders", ["id"])
    assert res["status"] == "denied" and res["row_count"] is None
    # tagged column: reader without fine-grained reader is denied by column
    res = emu.probe(RO, "", "retail", "customers", ["id", "email"])
    assert res["status"] == "denied" and "email" in res["reason"]
    res = emu.probe(RO, "", "retail", "customers", ["id", "full_name"])
    assert (res["status"], res["row_count"]) == ("ok", 0)
    res = emu.probe(RW, "", "retail", "customers", ["email"])
    assert res["status"] == "ok"
    # star expands to every column
    res = emu.probe(RO, "", "retail", "customers", ["*"])
    assert res["status"] == "denied"
    # unknown column is an error, never a pass
    res = emu.probe(RW, "", "retail", "customers", ["nope"])
    assert res["status"] == "error"
    # missing table is an error
    res = emu.probe(RW, "", "retail", "missing", ["id"])
    assert res["status"] == "error"

    # SESSION_USER() compares with the email part of the principal
    emu.run_ddl(AUDIT_DDL)
    emu.add_table_binding("retail", "audit_log", bb.ROLE_VIEWER, RO)
    emu.create_row_policy("retail", "audit_log", "rls_app_ro", [RO],
                          "actor = SESSION_USER()")
    audit = write_ndjson(tmp_path / "audit.ndjson.gz", [
        {"id": 1, "actor": "retail-app-ro@example.com", "action": "login"},
        {"id": 2, "actor": "someone@example.com"},
        {"id": 3, "actor": "retail-app-ro@example.com"}])
    emu.load_ndjson("retail", "audit_log", audit,
                    emu.get_table_schema("retail", "audit_log"))
    res = emu.probe(RO, "", "retail", "audit_log", ["id"])
    assert (res["status"], res["row_count"]) == ("ok", 2)

    # an unevaluable predicate is reported, never counted
    emu.create_row_policy("retail", "orders", "rls_weird", [RO],
                          "region LIKE 'e%'")
    res = emu.probe(RO, "", "retail", "orders", ["id"])
    assert res["status"] == "unevaluable" and res["row_count"] is None
    assert "region LIKE 'e%'" in res["reason"]

    ops = [l["op"] for l in read_log(tmp_path / "ops.log")]
    for expected in ("create_dataset", "run_ddl", "add_table_binding",
                     "add_dataset_access", "add_project_binding",
                     "create_taxonomy", "create_policy_tag",
                     "add_policy_tag_binding", "update_table_schema",
                     "create_row_policy", "load_ndjson"):
        assert expected in ops


def test_tamper_and_reopen(tmp_path):
    root = tmp_path / "emu"
    emu = bb.EmulatedBackend(root, PROJECT, "US")
    emu.create_dataset("retail")
    emu.run_ddl(CUSTOMERS_DDL)
    tax = emu.create_taxonomy("dbdrift_demo", ["FINE_GRAINED_ACCESS_CONTROL"])
    tag = emu.create_policy_tag(tax, "customers__email")
    emu.add_policy_tag_binding(tag, bb.ROLE_FGR, RW)
    emu.add_table_binding("retail", "customers", bb.ROLE_VIEWER, RW)
    fields = emu.get_table_schema("retail", "customers")
    fields[2]["policyTags"] = {"names": [tag]}
    emu.update_table_schema("retail", "customers", fields)
    assert emu.probe(RW, "", "retail", "customers", ["email"])["status"] == "ok"

    state = read_state(root)
    state["taxonomies"][tax]["policyTags"][tag]["bindings"] = []
    write_state(root, state)

    reopened = bb.EmulatedBackend(root, PROJECT, "US")
    assert reopened.get_policy_tag_bindings(tag) == []
    res = reopened.probe(RW, "", "retail", "customers", ["email"])
    assert res["status"] == "denied" and "email" in res["reason"]
    # everything else survived the round trip
    assert reopened.list_datasets() == ["retail"]
    assert reopened.get_table_bindings("retail", "customers") == [
        {"role": bb.ROLE_VIEWER, "member": RW}]
    assert reopened.describe_taxonomy(tax)["activatedPolicyTypes"] == [
        "FINE_GRAINED_ACCESS_CONTROL"]
    # and the taxonomy enforcement flag can be tampered too
    state["taxonomies"][tax]["activatedPolicyTypes"] = []
    write_state(root, state)
    assert bb.EmulatedBackend(root, PROJECT, "US").describe_taxonomy(tax)[
        "activatedPolicyTypes"] == []


