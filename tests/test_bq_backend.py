def test_query_fingerprint_imports_bq_validate_lazily(tmp_path, emu,
                                                      monkeypatch):
    calls = {}
    stub = types.ModuleType("db_drift.bq_validate")

    def fingerprint_from_rows(rows, spec):
        calls["rows"] = list(rows)
        calls["spec"] = spec
        return {"rows": str(len(calls["rows"]))}

    stub.fingerprint_from_rows = fingerprint_from_rows
    monkeypatch.setitem(sys.modules, "db_drift.bq_validate", stub)
    emu.create_dataset("retail")
    emu.run_ddl(ORDERS_DDL)
    emu.load_ndjson("retail", "orders",
                    write_ndjson(tmp_path / "o.ndjson.gz", ORDER_ROWS[:2]),
                    emu.get_table_schema("retail", "orders"))
    spec = [{"column": "id", "class": "number", "bq_type": "INT64"}]
    assert emu.query_fingerprint("retail", "orders", spec) == {"rows": "2"}
    assert calls["spec"] == spec and calls["rows"][1]["id"] == 2
    with pytest.raises(bb.BackendError, match="no SQL engine"):
        emu.query_json("SELECT 1")


