def test_live_probe_redacts_token(tmp_path):
    backend, runner = live(tmp_path, [
        (0, "tok-secret-value\n", ""),
        (0, '[{"n": "5"}]', "")])
    res = backend.probe(REPORTING, "probe@proj.iam.gserviceaccount.com",
                        "retail", "orders", ["id", "region"])
    assert res == {"status": "ok", "row_count": 5,
                   "reason": "5 rows as probe@proj.iam.gserviceaccount.com"}
    assert runner.calls[0] == (
        ["gcloud", "auth", "print-access-token",
         "--impersonate-service-account=probe@proj.iam.gserviceaccount.com"],
        None)
    argv, stdin = runner.calls[1]
    assert argv == BQ + ["--oauth_access_token=tok-secret-value", "query",
                         "--use_legacy_sql=false"]
    assert stdin == ("SELECT COUNT(*) AS n FROM (SELECT `id`, `region` "
                     "FROM `proj.retail.orders`)")
    text = (tmp_path / "ops.log").read_text(encoding="utf-8")
    assert "tok-secret-value" not in text
    assert "--oauth_access_token=<redacted>" in text
    ops = read_log(tmp_path / "ops.log")
    assert ops[-1]["op"] == "probe" and ops[-1]["status"] == "ok"

    # denied: stderr mentions Access Denied; the token never leaks
    runner.outputs.extend([(0, "tok-secret-value\n", ""),
                           (1, "", "BigQuery error in query operation: "
                                   "Access Denied: Table proj:retail.orders")])
    res = backend.probe(REPORTING, "probe@proj.iam.gserviceaccount.com",
                        "retail", "orders", [])
    assert res["status"] == "denied" and res["row_count"] is None
    assert "tok-secret-value" not in res["reason"]
    assert runner.calls[-1][1] == "SELECT COUNT(*) AS n FROM `proj.retail.orders`"
    # a permission complaint in stderr also counts as denied
    runner.outputs.extend([(0, "tok\n", ""),
                           (1, "", "User does not have permission to query")])
    assert backend.probe(RW, "sa@x", "retail", "orders", ["*"])["status"] \
        == "denied"
    assert runner.calls[-1][1] == \
        "SELECT COUNT(*) AS n FROM (SELECT * FROM `proj.retail.orders`)"
    # any other failure is an error, still without the token
    runner.outputs.extend([(0, "tok-secret-value\n", ""),
                           (1, "", "network unreachable")])
    res = backend.probe(RW, "sa@x", "retail", "orders", ["id"])
    assert res["status"] == "error" and "tok-secret-value" not in res["reason"]
    # no service account: nothing runs, honest status
    before = len(runner.calls)
    res = backend.probe(RW, "", "retail", "orders", ["id"])
    assert res["status"] == "unevaluable" and len(runner.calls) == before
    assert "tok-secret-value" not in (tmp_path / "ops.log").read_text(
        encoding="utf-8")


