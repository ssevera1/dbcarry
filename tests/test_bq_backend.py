def test_create_table_semantics(emu):
    with pytest.raises(bb.BackendError, match="retail"):
        emu.run_ddl(ORDERS_DDL)
    emu.create_dataset("retail")
    with pytest.raises(bb.BackendError, match="already exists"):
        emu.create_dataset("retail")
    emu.run_ddl(ORDERS_DDL)
    emu.run_ddl(ORDERS_DDL)   # IF NOT EXISTS is a no-op
    plain = ORDERS_DDL.replace("CREATE TABLE IF NOT EXISTS", "CREATE TABLE")
    with pytest.raises(bb.BackendError, match="already exists"):
        emu.run_ddl(plain)
    with pytest.raises(bb.BackendError, match="project"):
        emu.run_ddl("CREATE TABLE `other.retail.t` (id INT64)")
    # a dataset-qualified name without a project uses the backend project
    emu.run_ddl("CREATE TABLE retail.t2 (`order` STRING, n NUMERIC(10, 2))")
    assert emu.get_table_schema("retail", "t2") == [
        {"name": "order", "type": "STRING", "mode": "NULLABLE"},
        {"name": "n", "type": "NUMERIC", "mode": "NULLABLE"}]
    with pytest.raises(bb.BackendError, match="STRUCT"):
        emu.run_ddl("CREATE TABLE retail.t3 (s STRUCT<a INT64>)")
    with pytest.raises(bb.BackendError, match="clause"):
        emu.run_ddl("CREATE TABLE retail.t4 (s STRING) FROBNICATE")
    emu.delete_dataset("retail")
    assert emu.list_datasets() == []
    with pytest.raises(bb.BackendError):
        emu.delete_dataset("retail")


def test_update_table_schema_rules(emu):
    emu.create_dataset("retail")
    emu.run_ddl(CUSTOMERS_DDL)
    fields = emu.get_table_schema("retail", "customers")
    with pytest.raises(bb.BackendError, match="policy tag"):
        bad = [dict(f) for f in fields]
        bad[2]["policyTags"] = {"names": ["projects/proj/locations/US/"
                                          "taxonomies/9/policyTags/9"]}
        emu.update_table_schema("retail", "customers", bad)
    with pytest.raises(bb.BackendError, match="drop"):
        emu.update_table_schema("retail", "customers", fields[:2])
    with pytest.raises(bb.BackendError, match="type"):
        changed = [dict(f) for f in fields]
        changed[0]["type"] = "STRING"
        emu.update_table_schema("retail", "customers", changed)
    relaxed = [dict(f) for f in fields]
    relaxed[1]["mode"] = "NULLABLE"
    emu.update_table_schema("retail", "customers", relaxed)
    with pytest.raises(bb.BackendError, match="REQUIRED"):
        emu.update_table_schema("retail", "customers", fields)
    # adding a column is allowed; type aliases compare equal
    grown = [dict(f) for f in relaxed] + [
        {"name": "note", "type": "STRING", "mode": "NULLABLE"}]
    grown[0]["type"] = "INTEGER"
    emu.update_table_schema("retail", "customers", grown)
    assert len(emu.get_table_schema("retail", "customers")) == 4
    with pytest.raises(bb.BackendError):
        emu.update_table_schema("retail", "missing", fields)


def test_load_validates_rows_against_fields(tmp_path, emu):
    emu.create_dataset("retail")
    emu.run_ddl(CUSTOMERS_DDL)
    fields = emu.get_table_schema("retail", "customers")
    bad_col = write_ndjson(tmp_path / "a.ndjson", [
        {"id": 1, "full_name": "A", "email": "a@x", "bogus": 1}], gz=False)
    with pytest.raises(bb.BackendError, match="bogus"):
        emu.load_ndjson("retail", "customers", bad_col, fields)
    missing_req = write_ndjson(tmp_path / "b.ndjson.gz", [
        {"id": 1, "full_name": "A", "email": "a@x"},
        {"id": 2, "full_name": None, "email": "b@x"}])
    with pytest.raises(bb.BackendError, match="full_name"):
        emu.load_ndjson("retail", "customers", missing_req, fields)
    assert emu.count_rows("retail", "customers") == 0
    good = write_ndjson(tmp_path / "c.ndjson", [
        {"id": 1, "full_name": "A", "email": "a@x"}], gz=False)
    assert emu.load_ndjson("retail", "customers", good, fields) == 1
    # a second load appends, as bq load does by default
    assert emu.load_ndjson("retail", "customers", good, fields) == 2
    assert emu.count_rows("retail", "customers") == 2
    with pytest.raises(bb.BackendError, match="not found"):
        emu.load_ndjson("retail", "nope", good, fields)
    with pytest.raises(bb.BackendError, match="allUsers"):
        emu.add_table_binding("retail", "customers", bb.ROLE_VIEWER,
                              "allUsers")
    with pytest.raises(bb.BackendError, match="allAuthenticatedUsers"):
        emu.add_dataset_access("retail", {"role": bb.ROLE_VIEWER,
                                          "member": "allAuthenticatedUsers"})


