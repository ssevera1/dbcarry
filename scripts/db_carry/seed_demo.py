"""Seed the deterministic dbcarry demo dataset (RNG seed 42).

Data volumes are constants below; \\copy streams CSV from memory. After
copying with explicit ids, sequences are advanced with setval so the
source is internally consistent.
"""
import argparse
import csv
import datetime
import io
import json
import random
import re
import subprocess
import sys

from db_carry import pg

SEED = 42
N_CUSTOMERS = 100_000
N_PRODUCTS = 5_000
N_ORDERS = 200_000
N_AUDIT = 50_000
STATUSES = ["placed", "paid", "shipped", "delivered", "cancelled"]
REGIONS = ["us-east", "us-west", "eu"]

DDL = """
CREATE EXTENSION IF NOT EXISTS hstore;
CREATE TABLE customers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE,
  full_name text NOT NULL,
  created_at timestamptz NOT NULL
);
CREATE TABLE products (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  sku text NOT NULL UNIQUE,
  name text NOT NULL,
  price_cents integer NOT NULL CHECK (price_cents >= 0),
  attributes hstore
);
CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_id bigint NOT NULL REFERENCES customers(id),
  status text NOT NULL,
  ordered_at timestamptz NOT NULL,
  region text NOT NULL
);
CREATE INDEX orders_customer_idx ON orders(customer_id);
CREATE INDEX orders_at_idx ON orders(ordered_at);
CREATE TABLE order_items (
  order_id bigint NOT NULL REFERENCES orders(id),
  product_id bigint NOT NULL REFERENCES products(id),
  quantity integer NOT NULL,
  unit_price_cents integer NOT NULL,
  PRIMARY KEY (order_id, product_id)
);
CREATE TABLE audit_log (
  logged_at timestamptz NOT NULL,
  actor text,
  action text,
  detail text
);
CREATE VIEW recent_orders AS
  SELECT o.id, c.email, o.status, o.ordered_at
  FROM orders o JOIN customers c ON c.id = o.customer_id
  WHERE o.ordered_at > now() - interval '90 days';
"""

POST = """
CREATE MATERIALIZED VIEW sales_by_product AS
  SELECT p.id, p.sku, sum(oi.quantity) AS qty,
         sum(oi.quantity * oi.unit_price_cents) AS revenue_cents
  FROM order_items oi JOIN products p ON p.id = oi.product_id
  GROUP BY 1, 2;
DO $$ BEGIN
  BEGIN CREATE ROLE app_rw LOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
  BEGIN CREATE ROLE app_ro LOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
  BEGIN CREATE ROLE reporting NOLOGIN; EXCEPTION WHEN duplicate_object THEN NULL; END;
END $$;
GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO app_rw;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO app_rw;
GRANT SELECT ON ALL TABLES IN SCHEMA public TO app_ro;
GRANT SELECT ON sales_by_product, recent_orders TO reporting;
-- v0.2.0 planted security findings (see demo/scenario.md).
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
CREATE POLICY orders_region_eu ON orders FOR SELECT TO reporting
  USING (region = 'eu');
CREATE POLICY orders_all_rw ON orders TO app_rw USING (true);
ALTER TABLE audit_log ENABLE ROW LEVEL SECURITY;
CREATE POLICY audit_self ON audit_log FOR SELECT TO app_ro
  USING (actor = current_user);
CREATE POLICY audit_all_rw ON audit_log TO app_rw USING (true);
REVOKE SELECT ON customers FROM app_ro;
GRANT SELECT (id, full_name, created_at) ON customers TO app_ro;
GRANT app_ro TO reporting;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT SELECT ON TABLES TO app_ro;
SELECT setval(pg_get_serial_sequence('customers', 'id'),
              (SELECT max(id) FROM customers));
SELECT setval(pg_get_serial_sequence('products', 'id'),
              (SELECT max(id) FROM products));
SELECT setval(pg_get_serial_sequence('orders', 'id'),
              (SELECT max(id) FROM orders));
ANALYZE;
"""


def _csv(rows):
    buf = io.StringIO()
    writer = csv.writer(buf, lineterminator="\n")
    writer.writerows(rows)
    return buf.getvalue()


def _copy(ci, table_cols, rows):
    argv = [pg.find_bin("psql"), "-X", "-q", "-v", "ON_ERROR_STOP=1"] \
        + pg.conn_argv(ci) \
        + ["-c", f"\\copy {table_cols} FROM STDIN WITH (FORMAT csv)"]
    proc = subprocess.run(
        argv, input=_csv(rows), env=pg.build_env(ci),
        capture_output=True, text=True, encoding="utf-8")
    if proc.returncode != 0:
        raise pg.PgError(f"copy into {table_cols} failed: "
                         f"{proc.stderr.strip()[:800]}")


def gen_customers(rng):
    for i in range(1, N_CUSTOMERS + 1):
        yield (i, f"user{i}@example.com", f"Customer {i}",
               f"2024-01-01T00:00:00+00:00")


def gen_products(rng):
    for i in range(1, N_PRODUCTS + 1):
        attrs = f'"color"=>"{rng.choice(["red", "blue", "green"])}", ' \
                f'"weight_g"=>"{rng.randint(50, 5000)}"'
        yield (i, f"SKU-{i:05d}", f"Product {i}",
               rng.randint(100, 99900), attrs)


def gen_orders(rng):
    base = datetime.date(2025, 1, 1)
    for i in range(1, N_ORDERS + 1):
        day = rng.randint(0, 600)
        ordered_at = base + datetime.timedelta(days=day)
        yield (i, rng.randint(1, N_CUSTOMERS), rng.choice(STATUSES),
               f"{ordered_at.isoformat()}T00:00:00+00:00",
               rng.choice(REGIONS))


def gen_order_items(rng):
    for order_id in range(1, N_ORDERS + 1):
        n = 1 if order_id % 2 else 2  # exactly 300k rows total
        products = rng.sample(range(1, N_PRODUCTS + 1), n)
        for pid in products:
            yield (order_id, pid, rng.randint(1, 5), rng.randint(100, 99900))


def gen_audit(rng):
    for i in range(N_AUDIT):
        yield (f"2025-06-01T00:00:00+00:00", f"user{rng.randint(1, 500)}",
               rng.choice(["login", "update", "delete", "export"]),
               f"row {i}")


def main(argv):
    parser = argparse.ArgumentParser(prog="dbcarry.py seed")
    pg.add_conn_args(parser)
    args = parser.parse_args(argv[1:])
    ci = pg.conn_from_args(args)
    admin = dict(ci, dbname="postgres")
    try:
        if not re.match(r"^[a-z_][a-z0-9_]*$", ci["dbname"]):
            raise pg.PgError(
                f"invalid dbname {ci['dbname']!r}: must match "
                "^[a-z_][a-z0-9_]*$")
        exists = pg.query_rows(
            admin, f"SELECT 1 FROM pg_database WHERE datname='{ci['dbname']}'")
        if exists:
            raise pg.PgError(
                f"database {ci['dbname']} already exists; drop it or use "
                "a fresh instance")
        pg.run_sql(admin, f'CREATE DATABASE "{ci["dbname"]}"')
        rng = random.Random(SEED)
        pg.run_sql(ci, DDL)
        _copy(ci, "customers(id,email,full_name,created_at)",
              gen_customers(rng))
        _copy(ci, "products(id,sku,name,price_cents,attributes)",
              gen_products(rng))
        _copy(ci, "orders(id,customer_id,status,ordered_at,region)",
              gen_orders(rng))
        _copy(ci, "order_items(order_id,product_id,quantity,unit_price_cents)",
              gen_order_items(rng))
        _copy(ci, "audit_log(logged_at,actor,action,detail)", gen_audit(rng))
        pg.run_sql(ci, POST)
        counts = {}
        for table in ("customers", "products", "orders", "order_items",
                      "audit_log"):
            counts[table] = int(
                pg.query_rows(ci, f"SELECT count(*) FROM {table}")[0][0])
        print(json.dumps(counts, indent=2))
        return 0
    except pg.PgError as exc:
        print(f"SEED ERROR: {exc}", file=sys.stderr)
        return 1
    except (OSError, ValueError, KeyError, IndexError) as exc:
        print(f"SEED ERROR: {type(exc).__name__}: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    main(["seed"] + sys.argv[1:])
